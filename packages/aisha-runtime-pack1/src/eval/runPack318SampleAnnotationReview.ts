/**
 * Pack 3.18: Controlled Shadow Sample Annotation and Review
 * 
 * Demonstrates the out-of-band annotation of the sample evidence collected in Pack 3.17,
 * and the subsequent generation of a Pack 3.13 aggregation report.
 *
 * This script modifies the blank JSON annotation templates to simulate human operator review
 * according to the Pack 3.16 runbook guidelines, then loads them into a fresh store
 * alongside the original immutable raw payloads to generate the final review metrics.
 */

import * as fs from "fs";
import * as path from "path";
import { loadAnnotatedSnapshot } from "../research/shadowSessionSampling";
import { aggregateLaneEvidence } from "../research/shadowDataReview";
import type { ShadowEvidenceAnnotation } from "../research/shadowEvidenceStore";

async function main() {
  console.log("═══════════════════════════════════════════════════════════════");
  console.log("  Pack 3.18 — Controlled Shadow Sample Annotation & Review");
  console.log("═══════════════════════════════════════════════════════════════\n");

  const pack317Dir = path.join(__dirname, "../../artifacts/shadow_samples/pack3_17");
  const outDir = path.join(__dirname, "../../artifacts/shadow_samples/pack3_18_review");
  fs.mkdirSync(outDir, { recursive: true });

  const snapshotPath = path.join(pack317Dir, "shadow_snapshot.json");
  
  if (!fs.existsSync(snapshotPath)) {
    console.error("❌ Blocker: Pack 3.17 snapshot not found. Run Pack 3.17 first.");
    process.exit(1);
  }

  // 1. Annotate Associative Sample
  console.log("[1] Annotating associative sample template...");
  const assocTemplatePath = path.join(pack317Dir, "annotations_associative_template.json");
  const assocAnnotations: ShadowEvidenceAnnotation[] = JSON.parse(fs.readFileSync(assocTemplatePath, "utf8"));
  
  for (const ann of assocAnnotations) {
    // Simulate an operator fully reviewing the evidence and verifying it was a valid catch
    ann.operatorReviewed = true;
    ann.contradictionCaught = true; 
    ann.noiseFlagged = false;
    ann.noteGraphSizeLogged = true;
    ann.annotatedAt = new Date().toISOString();
  }

  const reviewedAssocPath = path.join(outDir, "annotations_associative_reviewed.json");
  fs.writeFileSync(reviewedAssocPath, JSON.stringify(assocAnnotations, null, 2), "utf8");

  // 2. Annotate Trace Sample
  console.log("[2] Annotating trace sample template...");
  const traceTemplatePath = path.join(pack317Dir, "annotations_trace_template.json");
  const traceAnnotations: ShadowEvidenceAnnotation[] = JSON.parse(fs.readFileSync(traceTemplatePath, "utf8"));

  for (const ann of traceAnnotations) {
    ann.operatorReviewed = true;
    ann.episodeSummaryPopulationRate = 0.95; // Simulated 95% episode summary coverage
    ann.noteGraphSizeLogged = true;
    ann.annotatedAt = new Date().toISOString();
  }

  const reviewedTracePath = path.join(outDir, "annotations_trace_reviewed.json");
  fs.writeFileSync(reviewedTracePath, JSON.stringify(traceAnnotations, null, 2), "utf8");

  // 3. Import and generate report
  console.log("[3] Importing annotated snapshot and generating Pack 3.13 report...");
  const storeAssoc = loadAnnotatedSnapshot(snapshotPath, reviewedAssocPath);
  const storeTrace = loadAnnotatedSnapshot(snapshotPath, reviewedTracePath);

  const reportAssoc = aggregateLaneEvidence("associative", storeAssoc.exportForReview("associative"));
  const reportTrace = aggregateLaneEvidence("trace", storeTrace.exportForReview("trace"));

  const fullReport = {
    _meta: {
      notice: "CONTROLLED SAMPLE EVIDENCE ONLY. NOT PRODUCTION REAL-SESSION EVIDENCE.",
      generatedAt: new Date().toISOString(),
      pack: "3.18"
    },
    associativeLane: reportAssoc,
    traceLane: reportTrace,
  };

  const reportPath = path.join(outDir, "reviewed_controlled_sample_report.json");
  fs.writeFileSync(reportPath, JSON.stringify(fullReport, null, 2), "utf8");
  console.log(`    Saved reviewed report: ${reportPath}`);

  // 4. Generate README
  const readmePath = path.join(outDir, "README.md");
  fs.writeFileSync(readmePath, `# Pack 3.18 Controlled Shadow Sample Review

**NOTICE: This is a CONTROLLED SAMPLE REVIEW ONLY.**
These artifacts were generated by annotating the controlled samples from Pack 3.17.

**WARNING: LIVE-PATH PROMOTION REMAINS DENIED.**
This does NOT satisfy the Pack 3.11 real-session promotion requirements, as the evidence volume is below the required operator-reviewed thresholds (e.g., requires >= 10 real entries) and was produced via a deterministic mock rather than live user sessions.

## Contents
- \`annotations_associative_reviewed.json\`: Simulated operator review for associative lane sample.
- \`annotations_trace_reviewed.json\`: Simulated operator review for trace lane sample.
- \`reviewed_controlled_sample_report.json\`: The final Pack 3.13 aggregation report proving the annotated overlays successfully integrate with the review layer without mutating raw payloads.
`, "utf8");

  console.log(`    Saved README: ${readmePath}`);
  console.log("\n✅ Pack 3.18 Sample Annotation Review Complete");
}

main().catch(console.error);
