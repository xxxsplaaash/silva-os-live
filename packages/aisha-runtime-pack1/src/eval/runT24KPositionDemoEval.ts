/**
 * T24 Runner — Pack 2.8 K_position Eval & Demo
 *
 * Runs all scenarios, emits scored side-by-side comparison, writes markdown report.
 * Exit code 1 if any hard failure (leakage, voice corruption, signal check failure).
 */
import * as assert from "node:assert";
import * as fs from "node:fs";
import * as path from "node:path";
import { SCENARIOS, runComparison, ScenarioResult } from "./t24KPositionDemoEval";

function renderScoreRow(label: string, baseline: number, shaped: number): string {
  const delta = shaped - baseline;
  const arrow = delta > 0 ? "▲" : delta < 0 ? "▼" : "=";
  return `| ${label} | ${baseline} | ${shaped} | ${arrow} ${delta > 0 ? "+" : ""}${delta} |`;
}

function renderReport(results: ScenarioResult[]): string {
  const lines: string[] = [];

  lines.push("# Pack 2.8 K_position Eval & Demo Report");
  lines.push("");
  lines.push("*Generated by runT24KPositionDemoEval.ts — deterministic stub generator outputs*");
  lines.push("");
  lines.push("Scoring rubric (all 0–10 except leakage/aggression/mismatch where 0 = clean):");
  lines.push("");
  lines.push("| Dimension | Meaning |");
  lines.push("|---|---|");
  lines.push("| directness | Response leads with action rather than preamble |");
  lines.push("| usefulness | Response addresses the user's actual request |");
  lines.push("| loopBreaking | Shaping reduces friction user pushed against |");
  lines.push("| voiceIntegrity | Response stays in AISHA's natural voice register |");
  lines.push("| visibleLeakage | Mechanism token in user-visible text (0 = clean) |");
  lines.push("| overAggression | Response overshoots and becomes curt/useless (0 = clean) |");
  lines.push("| topicMismatch | Response addresses wrong topic (0 = clean) |");
  lines.push("");
  lines.push("---");
  lines.push("");

  for (const r of results) {
    lines.push(`## ${r.scenarioId}`);
    lines.push("");
    lines.push(`**Description:** ${r.description}`);
    lines.push("");
    if (r.isNegativeCase) {
      lines.push("> **NEGATIVE/NEUTRAL CASE** — shaping must not produce fake improvement.");
      lines.push("");
    }
    lines.push(`**Shaping effect expected:** ${r.expectShapingEffect ? "Yes" : "No"}`);
    lines.push(`**Ablation applied:** \`${JSON.stringify(r.ablation)}\``);
    lines.push("");

    lines.push("### Baseline Output (unshaped)");
    lines.push("```");
    lines.push(r.baselineText);
    lines.push("```");
    lines.push("");

    lines.push("### Shaped Output (K_position active)");
    lines.push("```");
    lines.push(r.shapedText);
    lines.push("```");
    lines.push("");

    lines.push("### Score Comparison");
    lines.push("| Dimension | Baseline | Shaped | Delta |");
    lines.push("|---|---|---|---|");
    lines.push(renderScoreRow("directness", r.baselineScore.directness, r.shapedScore.directness));
    lines.push(renderScoreRow("usefulness", r.baselineScore.usefulness, r.shapedScore.usefulness));
    lines.push(renderScoreRow("loopBreaking", r.baselineScore.loopBreaking, r.shapedScore.loopBreaking));
    lines.push(renderScoreRow("voiceIntegrity", r.baselineScore.voiceIntegrity, r.shapedScore.voiceIntegrity));
    lines.push(renderScoreRow("visibleLeakage", r.baselineScore.visibleLeakage, r.shapedScore.visibleLeakage));
    lines.push(renderScoreRow("overAggression", r.baselineScore.overAggression, r.shapedScore.overAggression));
    lines.push(renderScoreRow("topicMismatch", r.baselineScore.topicMismatch, r.shapedScore.topicMismatch));
    lines.push("");

    lines.push("### Signal Checks");
    lines.push(`**Baseline:** ✅ ${r.baselineSignalsPassed.join(", ") || "(none)"} ${r.baselineSignalsFailed.length > 0 ? "❌ " + r.baselineSignalsFailed.join(", ") : ""}`);
    lines.push(`**Shaped:** ✅ ${r.shapedSignalsPassed.join(", ") || "(none)"} ${r.shapedSignalsFailed.length > 0 ? "❌ FAILED: " + r.shapedSignalsFailed.join(", ") : ""}`);
    lines.push("");
    lines.push("---");
    lines.push("");
  }

  return lines.join("\n");
}

async function main() {
  console.log("Starting T24 K_position Prototype Eval & Demo (Pack 2.8)...\n");

  const results: ScenarioResult[] = [];
  let totalPass = 0;
  let totalFail = 0;

  for (const scenario of SCENARIOS) {
    process.stdout.write(`Running [${scenario.id}]... `);
    try {
      const result = await runComparison(scenario);
      results.push(result);

      // ── Hard assertions (exit 1 on failure) ────────────────────────────────

      // 1. Zero leakage — absolute requirement
      assert.strictEqual(
        result.shapedScore.visibleLeakage,
        0,
        `[${scenario.id}] HARD FAIL: K_position mechanism token leaked into user-visible text`,
      );

      // 2. Zero over-aggression
      assert.strictEqual(
        result.shapedScore.overAggression,
        0,
        `[${scenario.id}] HARD FAIL: Shaping produced over-aggressive output tone`,
      );

      // 3. Voice integrity must not collapse (>=5 = acceptable minimum)
      assert.ok(
        result.shapedScore.voiceIntegrity >= 5,
        `[${scenario.id}] HARD FAIL: Voice integrity collapsed below minimum`,
      );

      // 4. For positive scenarios aiming for directness, directness must be better or equal
      if (result.expectShapingEffect && !result.isNegativeCase && scenario.id !== "SCENARIO_2_DEPTH_TOLERANCE_BREVITY") {
        assert.ok(
          result.shapedScore.directness >= result.baselineScore.directness,
          `[${scenario.id}] HARD FAIL: Expected shaping to maintain or improve directness`,
        );
      }

      // 5. Shaped signal checks must all pass
      assert.strictEqual(
        result.shapedSignalsFailed.length,
        0,
        `[${scenario.id}] HARD FAIL: Shaped signal(s) failed: ${result.shapedSignalsFailed.join(", ")}`,
      );

      // 6. Negative case: ablation must not have fired (unformed store cannot shape)
      if (result.isNegativeCase && !result.expectShapingEffect) {
        const firedAdjustments = result.ablation?.adjustmentsApplied.length ?? 0;
        assert.strictEqual(
          firedAdjustments,
          0,
          `[${scenario.id}] HARD FAIL: Shaping fired on negative/neutral case (faked improvement)`,
        );
      }

      console.log("✅ PASS");
      totalPass++;
    } catch (err: any) {
      console.log("❌ FAIL");
      console.log("   " + err.message);
      totalFail++;
    }
  }

  // Write report
  const report = renderReport(results);
  const outPath = path.resolve(__dirname, "../../DEMO_PACK_2_8_K_POSITION_EVAL.md");
  fs.writeFileSync(outPath, report, "utf8");

  console.log(`\nFinished T24 Eval. Passed: ${totalPass}, Failed: ${totalFail}`);
  console.log(`Demo artifact written to DEMO_PACK_2_8_K_POSITION_EVAL.md`);

  if (totalFail > 0) {
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
